#!/usr/bin/env python3
"""Rewrite the WEIGHTS-BEGIN/END block in carnivorus.c from a tuned .npz."""
import argparse, sys
import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument('npz')
ap.add_argument('--source', default='carnivorus.c')
args = ap.parse_args()

d = np.load(args.npz)
w_mg = np.rint(d['w_mg']).astype(int)
w_eg = np.rint(d['w_eg']).astype(int)

def fmt(name, arr):
    lines = [f'    static const int {name}[NF] = {{']
    for i in range(0, 512, 16):
        lines.append('        ' + ', '.join(str(x) for x in arr[i:i+16]) + ',')
    lines.append('    };')
    return '\n'.join(lines)

block = ('    /* WEIGHTS-BEGIN (regenerated by tests/apply_weights.py after tuning) */\n'
         + fmt('W0_MG', w_mg) + '\n' + fmt('W0_EG', w_eg) + '\n'
         + '    memcpy(w_mg, W0_MG, sizeof w_mg);\n    memcpy(w_eg, W0_EG, sizeof w_eg);\n'
         + '    /* WEIGHTS-END */')

src = open(args.source).read()
b = src.index('    /* WEIGHTS-BEGIN')
e = src.index('    /* WEIGHTS-END */') + len('    /* WEIGHTS-END */')
open(args.source, 'w').write(src[:b] + block + src[e:])
print('weights applied: mg0..7 =', list(w_mg[:8]))
